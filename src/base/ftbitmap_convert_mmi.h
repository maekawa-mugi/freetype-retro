static void
ft_bitmap_mmi_convert_mono_row( const FT_Byte* src,
                                FT_Byte*       dst,
                                FT_UInt        width )
{
  FT_UInt  x = 0;


  /* Table reads are 8-byte aligned and stores are 16-byte aligned.
   * We skip the bulk path for rows with unaligned destinations.
   */
  if ( ( (FT_ULong)dst & 15UL ) == 0 )
  {
    for ( ; width - x >= 16; x += 16 )
    {
      const FT_Byte*  low = ft_mmi_mono8[src[x >> 3]];
      const FT_Byte*  high = ft_mmi_mono8[src[(x >> 3) + 1]];
      FT_ULong        lo, hi, result;


      __asm__ volatile (
        ".set push\n\t"
        ".set noreorder\n\t"
        "ld     %0, 0(%3)\n\t"
        "ld     %1, 0(%4)\n\t"
        "nop\n\t"
        "pcpyld %2, %1, %0\n\t"
        "sq     %2, 0(%5)\n\t"
        ".set pop\n\t"
        : "=&r" ( lo ), "=&r" ( hi ), "=&r" ( result )
        : "r" ( low ), "r" ( high ), "r" ( dst + x )
        : "memory" );
    }
  }

  for ( ; x < width; ++x )
    dst[x] = (FT_Byte)( ( src[x >> 3] >> ( 7 - ( x & 7 ) ) ) & 1U );
}


static void
ft_bitmap_mmi_convert_gray2_row( const FT_Byte* src,
                                 FT_Byte*       dst,
                                 FT_UInt        width )
{
  FT_UInt  x = 0;


  if ( ( (FT_ULong)dst & 15UL ) == 0 )
  {
    for ( ; width - x >= 16; x += 16 )
    {
      const FT_Byte*  p0 = ft_mmi_gray2x4[src[(x >> 2)    ]];
      const FT_Byte*  p1 = ft_mmi_gray2x4[src[(x >> 2) + 1]];
      const FT_Byte*  p2 = ft_mmi_gray2x4[src[(x >> 2) + 2]];
      const FT_Byte*  p3 = ft_mmi_gray2x4[src[(x >> 2) + 3]];
      FT_ULong        l0, l1, h0, h1;


      __asm__ volatile (
        ".set push\n\t"
        ".set noreorder\n\t"
        "lwu    %0, 0(%4)\n\t"
        "lwu    %1, 0(%5)\n\t"
        "lwu    %2, 0(%6)\n\t"
        "lwu    %3, 0(%7)\n\t"
        "dsll32 %1, %1, 0\n\t"
        "dsll32 %3, %3, 0\n\t"
        "or     %0, %0, %1\n\t"
        "or     %2, %2, %3\n\t"
        "pcpyld %0, %2, %0\n\t"
        "sq     %0, 0(%8)\n\t"
        ".set pop\n\t"
        : "=&r" ( l0 ), "=&r" ( l1 ), "=&r" ( h0 ), "=&r" ( h1 )
        : "r" ( p0 ), "r" ( p1 ), "r" ( p2 ), "r" ( p3 ),
          "r" ( dst + x )
        : "memory" );
    }
  }

  for ( ; x < width; ++x )
    dst[x] = (FT_Byte)( ( src[x >> 2] >>
                         ( 6 - 2 * ( x & 3 ) ) ) & 3U );
}


/* Expand 8 GRAY4 source bytes into 16 destination bytes in one MMI
 * quadword.  PEXTLB with rs=$zero creates 8 little-endian halfwords
 * containing the source bytes.  PSRLH obtains each high nibble and
 * PSLLH 12 / PSRLH 4 places each low nibble in bits 8..11.  POR
 * produces exactly the MSB-first byte order of the scalar routine.
 *
 * Use only aligned LD/SQ and do not read beyond the source row.
 * R5900 is little-endian in the intended PS2 execution environment.
 */
static void
ft_bitmap_mmi_convert_gray4_row( const FT_Byte* src,
                                 FT_Byte*       dst,
                                 FT_UInt        width )
{
  FT_UInt  x = 0;


  if ( ( (FT_ULong)dst & 15UL ) == 0 &&
       ( (FT_ULong)src & 7UL ) == 0 )
  {
    for ( ; width - x >= 16; x += 16 )
    {
      FT_ULong  unpacked, high_nibbles;


      __asm__ volatile (
        ".set push\n\t"
        ".set noreorder\n\t"
        "ld     %0, 0(%2)\n\t"
        "nop\n\t"
        "pextlb %0, $zero, %0\n\t"
        "psrlh  %1, %0, 4\n\t"
        "psllh  %0, %0, 12\n\t"
        "psrlh  %0, %0, 4\n\t"
        "por    %0, %0, %1\n\t"
        "sq     %0, 0(%3)\n\t"
        ".set pop\n\t"
        : "=&r" ( unpacked ), "=&r" ( high_nibbles )
        : "r" ( src + ( x >> 1 ) ), "r" ( dst + x )
        : "memory" );
    }
  }

  for ( ; x < width; ++x )
  {
    FT_Byte  val = src[x >> 1];


    dst[x] = (FT_Byte)( x & 1 ? val & 15U : val >> 4 );
  }
}

